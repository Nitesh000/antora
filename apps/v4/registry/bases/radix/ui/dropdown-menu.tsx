"use client"

import * as React from "react"
import { cn } from "cn"
import { DropdownMenu as DropdownMenuPrimitive } from "radix-ui"
import { motion, AnimatePresence } from "motion/react"

import { IconPlaceholder } from "@/app/(create)/components/icon-placeholder"

const fluidPop = { type: "spring", stiffness: 400, damping: 25, mass: 0.9 }
const fluidPress = { type: "spring", stiffness: 600, damping: 20, mass: 1 }

const DropdownMenuContext = React.createContext<{ isOpen: boolean }>({ isOpen: false })

function DropdownMenu({
  open: controlledOpen,
  defaultOpen,
  onOpenChange,
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Root>) {
  const [internalOpen, setInternalOpen] = React.useState(defaultOpen ?? false)
  const isOpen = controlledOpen !== undefined ? controlledOpen : internalOpen

  return (
    <DropdownMenuContext.Provider value={{ isOpen }}>
      <DropdownMenuPrimitive.Root
        data-slot="dropdown-menu"
        open={isOpen}
        onOpenChange={(val) => {
          if (controlledOpen === undefined) {
            setInternalOpen(val)
          }
          onOpenChange?.(val)
        }}
        {...props}
      />
    </DropdownMenuContext.Provider>
  )
}

function DropdownMenuPortal({
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Portal>) {
  return (
    <DropdownMenuPrimitive.Portal data-slot="dropdown-menu-portal" {...props} />
  )
}

